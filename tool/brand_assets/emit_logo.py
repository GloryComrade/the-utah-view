"""Turn logo.json (from vectorize_logo.py) into the Dart data block and SVG.

Usage: emit_logo.py <logo.json> <out_dir>  (see vectorize_logo.py for the pipeline)
"""
import json, sys
d = json.load(open(sys.argv[1])); out = sys.argv[2]
n = lambda v: (f"{v:.2f}").rstrip("0").rstrip(".")
def path_d(shapes):
    return " ".join("M" + " L".join(f"{n(x)} {n(y)}" for x, y in ring) + " Z" for rings in shapes for ring in rings)
red_d, white_d = path_d(d["red"]), path_d(d["white"])
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">'
       f'<path fill="#FFFFFF" d="{white_d}"/>'
       f'<path fill="{d["color"]}" fill-rule="evenodd" d="{red_d}"/></svg>\n')
open(f"{out}/logo.svg", "w").write(svg)
def dart_shapes(shapes):
    lines = []
    for rings in shapes:
        lines.append("  [")
        for ring in rings:
            lines.append("    [" + ", ".join(f"{n(x)}, {n(y)}" for x, y in ring) + "],")
        lines.append("  ],")
    return "\n".join(lines)
dart = ("// ── Generated by tool/brand_assets/vectorize_logo.py — do not edit by hand. ──\n"
        "// The mark in a 100×100 box (filling 4..96). Each shape is a list of rings\n"
        "// (x, y pairs); the first ring is the outline, any others are holes.\n\n"
        "/// The white counters behind the mark: the gap between the brackets and the\n"
        "/// inner square.\n"
        f"const _kLogoWhite = <List<List<double>>>[\n{dart_shapes(d['white'])}\n];\n\n"
        "/// The red brackets, square frame and \"UT\".\n"
        f"const _kLogoRed = <List<List<double>>>[\n{dart_shapes(d['red'])}\n];\n")
open(f"{out}/logo_data.dart", "w").write(dart)
print(len(svg), "bytes svg;", d["color"])
